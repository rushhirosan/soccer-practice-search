from __future__ import annotations

from datetime import datetime
from typing import Any

SUPPORTED_LOCALES = frozenset({"ja", "en"})
DEFAULT_LOCALE = "ja"
UI_LOCALE_COOKIE = "ui_locale"
UI_LOCALE_SESSION_KEY = "ui_locale"


def resolve_locale(request: Any, session: Any) -> str:
    """Pick UI locale: session (set from ?lang= in before_request) > cookie > Accept-Language > ja."""
    s = session.get(UI_LOCALE_SESSION_KEY)
    if isinstance(s, str) and s.lower() in SUPPORTED_LOCALES:
        return s.lower()
    c = request.cookies.get(UI_LOCALE_COOKIE)
    if isinstance(c, str) and c.lower() in SUPPORTED_LOCALES:
        return c.lower()
    best = request.accept_languages.best_match(["ja", "en"])
    if best in SUPPORTED_LOCALES:
        return best
    return DEFAULT_LOCALE


def t(locale: str, key: str, **kwargs: Any) -> str:
    row = STRINGS.get(key)
    if not row:
        return key
    loc = locale if locale in SUPPORTED_LOCALES else DEFAULT_LOCALE
    text = row.get(loc) or row.get("ja") or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def js_bundle(locale: str) -> dict[str, str]:
    loc = locale if locale in SUPPORTED_LOCALES else DEFAULT_LOCALE
    return {k: (v.get(loc) or v.get("ja") or "") for k, v in STRINGS.items() if k in JS_KEYS}


def formation_display_map(locale: str) -> dict[str, str]:
    """Map internal formation / count labels (Japanese) to display label."""
    if locale != "en":
        return {}
    return dict(FORMATION_DISPLAY_EN)


def format_catalog_freshness_date(dt: datetime, locale: str) -> str:
    """Short date for header catalog freshness badge."""
    loc = locale if locale in SUPPORTED_LOCALES else DEFAULT_LOCALE
    if loc == "en":
        return dt.strftime("%b %d, %Y")
    return dt.strftime("%Y/%m/%d")


